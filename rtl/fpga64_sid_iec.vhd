-- AND baLoc, which is the one place this cannot simply mirror the 6510. A 6502
-- halts on a read when RDY goes low but COMPLETES a write, which is why
-- phi0_cpu above forces cpuHasBus whenever cpuWe is high. The 65C816 core does
-- not work that way: RDY_IN gates its whole enable, so when the VIC takes the
-- bus the core freezes with every output held, cpuWe among them -- and that
-- forced cpuHasBus then commits the same write on all 43 stolen cycles. For RAM
-- it is idempotent and invisible. For anything that COUNTS writes -- the
-- RAMLink SDRAM path, vdrives, the CMD HD, the REU, any FIFO or strobe -- one
-- store becomes forty-four.
--
-- Gating on baLoc is not dropping the write. The core has not advanced, so the
-- write has not happened yet; it is re-presented and committed on the cycle
-- after the VIC gives the bus back. It also stops this CPU taking cycles back
-- off the VIC, which the 6510 accommodation only exists to allow.
cpuWe_pre   <= cpuWe_6510   when scpu_enable = '0' else
               (cpuWe_816 and busCyc_816 and baLoc and not scpu_mem_hit);
cpuIO       <= cpuIO_6510   when scpu_enable = '0' else cpuIO_816;
nmi_ack     <= nmiAck_6510  when scpu_enable = '0' else nmiAck_816;
scpu_bank   <= bank_816;
scpu_vpb    <= vpb_816;
scpu_emul   <= emul_816;
cia1_irq_n_o <= irq_cia1;
scpu_io_o   <= '1' when cpuIO(2) = '1' and (cpuIO(0) = '1' or cpuIO(1) = '1') else '0';

-- What the 65C816 reads: its own ROM, its own shadow, or the C64 bus.
scpu_di     <= scpu_rom_q    when scpu_rom_hit = '1'    else
               scpu_shadow_q when scpu_shadow_hit = '1' else
               cpuDi;

cass_motor <= cpuIO(5);
cass_write <= cpuIO(3);

ramDout <= cpuDo;
ramAddr <= systemAddr;
ramWE   <= systemWe when sysCycle >= CYCLE_CPU0 else '0';

-- 4/7/23 by sy2002: added "and (romL = '0' and romH = '0' and UMAXromH = '0')"
-- Without this addition, the chip select is active when it should not be. When working with real cartridges,
-- this for example led to EasyProg overwriting itself while flashing a cartridge
-- 6/29/25 by sy2002: To fix https://github.com/MJoergen/C64MEGA65/issues/176, we must ensure
-- that UMAXnomap does not trigger a RAM chip enable, so that writes go to a the cartridge's RAM for example
-- in the case of an IDE64
ramCE   <= cs_ram when (sysCycle = CYCLE_VIC0 or cpu_cyc = '1') and (romL = '0' and romH = '0' and UMAXromH = '0' and UMAXnomap = '0') else '0';

-- 6/7/26 by sy2002:
--
-- C64MEGA65 turbo-mode protection for hardware cartridges:
-- https://github.com/MJoergen/C64MEGA65/issues/87#issuecomment-4643004168
--
-- The CPU0/4/8 turbo conjuncts use cs_turbo_eligible instead of the overloaded cs_ram
-- so that hardware-cartridge accesses cannot trigger an early CPU advance and break
-- the cart's PHI2 timing. The CYCLE_CPUC clause stays on cs_ram so that a hardware-cart
-- access still completes at the natural 1 MHz slot.
cpu_cyc <= '1' when
				(sysCycle = CYCLE_CPU0 and turbo_m(0) = '1' and cs_turbo_eligible = '1' ) or
				(sysCycle = CYCLE_CPU4 and turbo_m(1) = '1' and cs_turbo_eligible = '1' ) or
				(sysCycle = CYCLE_CPU8 and turbo_m(2) = '1' and cs_turbo_eligible = '1' ) or
				(sysCycle = CYCLE_CPUC and (io_enable = '1'  or cs_ram = '1')) else '0';
				
process(clk32)
begin
	if rising_edge(clk32) then
		cpu_cyc_s <= cpu_cyc_s(0) & cpu_cyc;
		enableCpu <= cpu_cyc_s(1);
		io_enable <= io_enable and not enableCpu;

		if sysCycle = CYCLE_EXT0 then
			io_enable <= '1';
		end if;

		-- 2 points to register DMA request before CPU cycles.
		if sysCycle = CYCLE_EXT1 or sysCycle = CYCLE_EXT5 then
			dma_active <= dma_req;
			turbo_en <= turbo_mode(0);
			turbo_m <= "000";
			if dma_req = '0' and ((turbo_mode(0) and turbo_state) = '1' or turbo_mode(1) = '1') then
				case turbo_speed is
					when "00" => turbo_m <= "010";
					when "01" => turbo_m <= "110";
					when "10" => turbo_m <= "111";
					when "11" => turbo_m <= "111"; -- unused
					when others => turbo_m <= "111"; -- metavalues, for simulation
				end case;
			end if;
		end if;
	end if;
end process;

cpuAddr <= cpuAddr_pre when dma_active = '0' else dma_addr;
cpuDo   <= cpuDo_pre   when dma_active = '0' else dma_dout;
cpuWe   <= cpuWe_pre   when dma_active = '0' else dma_we;

ext_cycle <= '1' when (sysCycle >= CYCLE_DMA0 and sysCycle <= CYCLE_DMA3) else '0';
dma_cycle <= '1' when (sysCycle >= CYCLE_CPU0 and sysCycle <= CYCLE_CPUF) and cpuHasBus = '1' and dma_active = '1' else '0';
dma_din   <= cpuDi;

end architecture;

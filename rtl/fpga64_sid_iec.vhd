-- A 65C816 cycle only means something on the bus when it says so. VDA and VPA
-- are both low during the processor's internal cycles, when the address bus
-- carries whatever was left on it -- and those cycles are READS, because the
-- core drives WE low only while OUT_BUS is non-zero. A stray read is not
-- harmless on a C64: $DC0D and $DD0D clear the CIA interrupt flags when read,
-- so one landing there eats an interrupt and the machine hangs somewhere
-- unrelated. Internal cycles are therefore pointed at $0100, which is RAM in
-- every memory configuration and has no side effect.
--
-- Bank 0 only, as well. There is no SuperRAM yet, so nothing above bank 0
-- exists; a write there is dropped rather than folded back into bank 0, which
-- is what unpopulated memory does. Reads outside bank 0 alias into bank 0.
busCyc_816 <= (vda_816 or vpa_816) when bank_816 = x"00" else '0';

-- -----------------------------------------------------------------------
-- MEGA65 (CMD SuperCPU): where a 65C816 access is actually answered.
--
-- Banks $00 and $01 are the accelerator's static RAM on the real board and
-- $F8/$F9 are its system ROM. Bank $00 is not duplicated here: the C64's own
-- RAM is already single-cycle block RAM, so bank $00 simply is that RAM and
-- the VIC sees every write without any mirroring. Bank $01 is the OS shadow
-- and bank $F8 is the ROM, both in main.vhd.
--
-- Three rules, in order:
--   * bank $F8 reads come from the ROM.
--   * bank $01 is the shadow, read and written.
--   * bank $00 reads come from the ROM while bootmap is set -- which is how the
--     reset vector at $00:FFFC can be fetched before anything has been copied
--     anywhere -- and afterwards, once the shadow holds the operating system,
--     a read of the address range the PLA maps BASIC or KERNAL into is answered
--     from the shadow instead of from the C64's own ROM. That is the
--     "multi-layered KERNAL" the CMD manual warns about, and it is why copying
--     the KERNAL to RAM and running it there fails on a real SuperCPU.
-- Everything else is the ordinary C64 bus.
-- I/O ALWAYS GOES OUT TO THE BUS. Neither bootmap nor the shadow may cover
-- $D000-$DFFF while the chips are banked in: the accelerator's own registers
-- live there, and so do the VIC and the CIAs. Without this the boot ROM's very
-- first decision -- BIT $D0B0 / BVS, which asks whether this is a 64 or a 128 --
-- reads ROM instead of the register, takes the 128 branch, sets $01 to $E3 and
-- never recovers. CMD put it plainly: "Mirroring of I/O is always performed
-- when I/O is mapped in."
scpu_io_win     <= '1' when cpuAddr_816(15 downto 12) = x"D" and
                            cpuIO(2) = '1' and (cpuIO(0) = '1' or cpuIO(1) = '1') else '0';

-- WHAT BOOTMAP ACTUALLY COVERS: $8000-$CFFF and $E000-$FFFF, and nothing below
-- $8000. Not the whole of bank $00, which is what this used to say.
--
-- VICE builds the map as a table per 4 kB area against the PLA configuration
-- byte, and bit 7 of that byte is bootmap (scpu64meminit.c, with
-- mem_pla_config_changed in scpu64mem.c assembling the index). Reading the
-- table out for one configuration, with bootmap clear and set:
--
--      0000-0fff   RAM            RAM
--      1000-5fff   RAM            RAM
--      6000-7fff   RAM            RAM
--      8000-9fff   ROML           $F8
--      a000-bfff   ROMH           $F8
--      c000-cfff   RAM            $F8
--      d000-d7ff   I/O            I/O
--      d800-dbff   colour RAM     colour RAM
--      dc00-dfff   I/O            I/O
--      e000-ffff   kernal shadow  $F8
--
-- So bootmap leaves the bottom 32 kB alone, and THE STACK IS IN THE BOTTOM
-- 32 kB. Covering all of bank $00 broke the boot ROM in a way that took a long
-- time to find, because writes still went to RAM: the ROM pushes a return
-- address at $01FE/$01FF when it calls its checksum at $0176, the two writes
-- land in RAM correctly, and 1.1 million cycles later the RTS reads the same
-- two addresses out of the EPROM instead and gets $05/$70 -- the bytes that
-- happen to sit at $F8:01FE. $0570 is not even an instruction boundary; it is
-- the middle of STA $D0B2, so the processor ran its operand bytes as a BNE,
-- fell into the RTL after it, pulled three more EPROM bytes and left for bank
-- $8D, where it executed $AA as TAX until the run ended. Nothing looked wrong
-- until the very last step, and every self-test passed on the way.
--
-- The $D000-$DFFF hole is unconditional in the table -- with CHAREN clear that
-- area is the character ROM, never the EPROM -- so scpu_io_win above only has
-- to decide between I/O and the C64 bus, not whether bootmap applies.
scpu_boot_win   <= '1' when cpuAddr_816(15) = '1' and cpuAddr_816(15 downto 12) /= x"D" else '0';
scpu_basic_sel  <= '1' when cpuAddr_816(15 downto 13) = "101" and cpuIO(0) = '1' and cpuIO(1) = '1' else '0';
scpu_kernal_sel <= '1' when cpuAddr_816(15 downto 13) = "111" and cpuIO(1) = '1' else '0';

-- Every one of these is gated on scpu_shadow_on, which main.vhd drives from
-- "QNICE has actually streamed a SuperCPU ROM in". Without one there is nothing
-- at bank $F8 and nothing in the shadow, and bootmap would otherwise point the
-- processor at an empty block RAM from its very first fetch. With no ROM the
-- accelerator runs the stock C64 map, which is the mode that works today.
-- THE INTERRUPT VECTOR REROUTE. A SuperCPU does not always take its interrupt
-- vectors from page $FF of bank $00: under the conditions below it reads them
-- from bank $F8 instead, so $FFFE becomes $F8:FFFE. In ROM 2.04 that holds
-- $FC94, which is a JML to $00:FBE1, and that lands in the Enhanced Interrupt
-- Redirection Jump Table at $01:FC80-$FCAF. Without this the processor takes
-- the stock KERNAL vector and the redirection table is never reached.
--
-- VICE computes it in scpu64mem.c:1741, and the two clauses are independent:
--
--   (_mem_read_tab_ptr[0xff] == scpu64_kernalshadow_read ||
--    _mem_read_tab_ptr[0xff] == ram1_read)
--   && (!scpu64_emulation_mode || mem_reg_hwenable || mem_reg_sys_1mhz ||
--       mem_reg_dosext || mem_reg_ramlink)
--
-- The first clause asks where a read of page $FF would have gone, which here is
-- the same question as whether the shadow serves $E000-$FFFF: bootmap off and
-- the KERNAL selected. The second is a plain OR of five flags, four of them
-- registers in supercpu.vhd and the fifth the presence of a RAMLink.
--
-- Note what the second clause means in practice. In emulation mode with no
-- RAMLink and nothing else set it is false, so a bare SuperCPU keeps the stock
-- vectors -- which is why the boot handover works without any of this. Plug a
-- RAMLink in and mem_reg_ramlink is permanently 1, so the reroute is always on
-- and every interrupt the machine takes goes somewhere we were not sending it.
-- The condition is its own entity so that it can be simulated: this one cannot
-- be, as GHDL will not bind it (the CIAs are Verilog) and xsim corrupts its
-- heap during initialisation on it. See tb_scpu_vec_reroute.
scpu_bank00 <= '1' when bank_816 = x"00" else '0';


-- -----------------------------------------------------------------------
-- Local signal to outside world
-- -----------------------------------------------------------------------
ba <= baLoc; -- Added 260224 by MFJ

io_cycle <= '1' when
	(sysCycle >= CYCLE_EXT0 and sysCycle <= CYCLE_EXT3) or
	(sysCycle >= CYCLE_EXT4 and sysCycle <= CYCLE_EXT7 and rfsh_cycle /= "00")  else '0';

-- -----------------------------------------------------------------------
-- System state machine, controls bus accesses
-- and triggers enables of other components
-- -----------------------------------------------------------------------

sysCycle <= preCycle when sysEnable = '1' else CYCLE_EXT4;
pause_out <= not sysEnable;

process(clk32)
begin
	if rising_edge(clk32) then
		preCycle <= sysCycleDef'succ(preCycle);
		if preCycle = sysCycleDef'high then
			preCycle <= sysCycleDef'low;
			if sysEnable = '1' then
				rfsh_cycle <= rfsh_cycle + 1;
			end if;
		end if;
		
		refresh <= '0';
		if preCycle = sysCycleDef'pred(CYCLE_EXT4) and rfsh_cycle = "00" then
			sysEnable <= not pause;
			refresh <= '1';
		end if;
	end if;
end process;

process(clk32)
begin
	if rising_edge(clk32) then
		if preCycle = sysCycleDef'high then
			reset <= not reset_n;
		end if;
	end if;
end process;

-- PHI0-clock emulation
process(clk32)
begin
	if rising_edge(clk32) then
		if sysCycle = sysCycleDef'pred(CYCLE_CPU0) then
			phi0_cpu <= '1';
			if baLoc = '1' or (cpuWe = '1' and dma_active = '0') or (ba_dma = '1' and dma_active = '1') then
				cpuHasBus <= '1';
			end if;
		end if;
		if sysCycle = sysCycleDef'high then
			phi0_cpu <= '0';
			cpuHasBus <= '0';
		end if;
	end if;
end process;

process(clk32)
begin
	if rising_edge(clk32) then
		enableVic <= '0';
		enableCia_n <= '0';
		enableCia_p <= '0';
		enableSid <= '0';

		case sysCycle is
		when CYCLE_VIC2 =>
			enableVic <= '1';
		when CYCLE_CPUE =>
			enableVic <= '1';
		when CYCLE_CPUC =>
			enableCia_n <= '1';
		when CYCLE_CPUF =>
			enableCia_p <= '1';
			enableSid <= '1';
		when others =>
			null;
		end case;
	end if;
end process;

-- Expansion Port-faithful PHI2 generation (sy2002 26/05/03)
-- 
-- This signal is routed to the cart port (cart_phi2_o) via main.vhd. Its
-- timing reproduces real-C64 PHI2 behavior at the cart connector:
--
--   * Rises at edge into CYCLE_CPU1, one sysCycle AFTER phi0_cpu rises.
--     This gives the cart's address sampling a settled bus to look at.
--     Real C64 PHI2 also trails the CPU's bus-takeover slightly due to
--     the 6510's internal propagation delay.
--
--   * Falls at edge into CYCLE_CPUF, one sysCycle BEFORE the CPU commits
--     its next-cycle address (which happens at edge into CYCLE_EXT0 of the
--     next iteration). This provides ~31 ns of address hold time after PHI2
--     falls, matching the real C64's tAH (~30 ns).
--
--   * High duration: CYCLE_CPU1 through CYCLE_CPUE = 14 sysCycles ≈ 437 ns,
--     safely above the 6510 datasheet minimum tPWH of 400 ns.

process(clk32)
begin
  if rising_edge(clk32) then
    case sysCycle is
      when CYCLE_CPU0 =>
        phi2 <= '1';
      when CYCLE_CPUE =>
        phi2 <= '0';
      when others =>
        null;
    end case;
  end if;
end process;

